char    *ft_strncpy(char *dest, char *src, unsigned int n)
{
    char *ptr = dest;

    while (n > 0 && *src != '\0')
    {
        *ptr++ = *src++;
        n--;
    }
    while (n > 0)
    {
        *ptr++ = '\0';
        n--;
    }
    return dest;
}
